function extractContextSnippet(text: string, index: number, length: number): string {
  const start = Math.max(0, index - 80);
  const end = Math.min(text.length, index + length + 100);
  return text.slice(start, end).replace(/\s+/g, ' ').trim();
}

export function verifyCitationsInText(
  documentText: string,
  uploadedReferenceText?: string
): CitationVerificationReport {
  const items: CitationVerificationItem[] = [];
  const consumedSpans: Array<[number, number]> = [];

  const isOverlapping = (start: number, end: number) =>
    consumedSpans.some(([s, e]) => start < e && end > s);

  const statutoryRegex =
    /\b(?:Section|Sec\.?|S\.)\s*(\d+[A-Za-z]?)\s*(?:(?:\([0-9a-zA-Z]+\))*\s*)?(?:of\s+the\s+|,\s*|\s+under\s+the\s+|\s+read\s+with\s+)?([A-Z][A-Za-z\s]+?Act(?:,\s*\d{4}|\s+\d{4})?)\b/g;

  let match: RegExpExecArray | null;
  while ((match = statutoryRegex.exec(documentText)) !== null) {
    const rawCitation = match[0].trim();
    const sectionToken = match[1].trim();
    const sectionNum = parseInt(sectionToken, 10);
    const actRaw = match[2].trim();
    const startIdx = match.index;
    const endIdx = startIdx + rawCitation.length;

    if (isOverlapping(startIdx, endIdx)) continue;
    consumedSpans.push([startIdx, endIdx]);

    const contextSnippet = extractContextSnippet(documentText, startIdx, rawCitation.length);
    const lowerContext = contextSnippet.toLowerCase();

    // Step 1: Check against LEGAL_CORPUS_RECORDS (exact Act + exact Section)
    const matchedRecord = LEGAL_CORPUS_RECORDS.find((rec) => {
      const sameSection =
        rec.sectionOrRule.toLowerCase() === `section ${sectionToken.toLowerCase()}`;
      const sameAct =
        actRaw.toLowerCase().includes(rec.actOrCaseName.split(',')[0].toLowerCase()) ||
        rec.actOrCaseName.toLowerCase().includes(actRaw.split(',')[0].toLowerCase());
      return sameSection && sameAct;
    });

    if (matchedRecord) {
      const contextMatchesSubject = matchedRecord.subjectKeywords.some((kw) =>
        lowerContext.includes(kw.toLowerCase())
      );

      if (contextMatchesSubject) {
        items.push({
          rawCitation,
          normalizedCitation: matchedRecord.canonicalCitation,
          status: 'Verified',
          evidenceOrigin: 'Local Corpus',
          evidenceBasis: 'Corpus Match + Verbatim Excerpt',
          explanation: `Matched ${matchedRecord.canonicalCitation} in the local legal corpus, and the surrounding draft context aligns with the provision's statutory subject matter (${matchedRecord.summary}).`,
          limitationNote:
            'Matched against the local statutory corpus excerpt with official India Code reference URL. Currentness against recent legislative amendments is not claimed unless checked online.',
          contextSnippet,
          matchedRecord: {
            id: matchedRecord.id,
            canonicalCitation: matchedRecord.canonicalCitation,
            actOrCaseName: matchedRecord.actOrCaseName,
            sectionOrRule: matchedRecord.sectionOrRule,
            summary: matchedRecord.summary,
            verbatimExcerpt: matchedRecord.verbatimExcerpt,
            officialSourceUrl: matchedRecord.officialSourceUrl,
            officialSourceLabel: matchedRecord.officialSourceLabel
          }
        });
      } else {
        items.push({
          rawCitation,
          normalizedCitation: matchedRecord.canonicalCitation,
          status: 'Partially Verified',
          evidenceOrigin: 'Local Corpus',
          evidenceBasis: 'Corpus Match — Context Diverges',
          explanation: `The citation ${matchedRecord.canonicalCitation} exists in the local corpus (${matchedRecord.summary}), but the surrounding sentence in the draft does not contain expected subject-matter keywords. Verify that this section applies to the stated proposition.`,
          limitationNote:
            'Never marked Verified solely because the section number exists; contextual alignment check flagged a potential mismatch.',
          contextSnippet,
          matchedRecord: {
            id: matchedRecord.id,
            canonicalCitation: matchedRecord.canonicalCitation,
            actOrCaseName: matchedRecord.actOrCaseName,
            sectionOrRule: matchedRecord.sectionOrRule,
            summary: matchedRecord.summary,
            verbatimExcerpt: matchedRecord.verbatimExcerpt,
            officialSourceUrl: matchedRecord.officialSourceUrl,
            officialSourceLabel: matchedRecord.officialSourceLabel
          }
        });
      }
      continue;
    }

    // Step 2: Check if the Act is in RECOGNIZED_STATUTES
    const recognizedStatute = RECOGNIZED_STATUTES.find((st) => st.namePattern.test(actRaw));
    if (recognizedStatute) {
      if (isNaN(sectionNum) || sectionNum < 1 || sectionNum > recognizedStatute.maxSection) {
        items.push({
          rawCitation,
          normalizedCitation: `Section ${sectionToken}, ${recognizedStatute.canonicalActName}`,
          status: 'Unverified',
          evidenceOrigin: 'Local Corpus',
          evidenceBasis: 'Out-of-Range / Non-Existent Section in Known Act',
          explanation: `Non-existent section number: Section ${sectionToken} exceeds the enacted statutory range (Sections 1–${recognizedStatute.maxSection}) of the ${recognizedStatute.canonicalActName}.`,
          limitationNote:
            'Flagged as Unverified because the cited section number falls outside the statute bounds.',
          contextSnippet,
          matchedRecord: {
            id: `statute-bounds-${recognizedStatute.canonicalActName}`,
            canonicalCitation: recognizedStatute.canonicalActName,
            actOrCaseName: recognizedStatute.canonicalActName,
            sectionOrRule: `Valid Range: Sections 1–${recognizedStatute.maxSection}`,
            summary: `Section ${sectionToken} is outside the enacted bounds of ${recognizedStatute.canonicalActName}.`,
            officialSourceUrl: recognizedStatute.officialSourceUrl,
            officialSourceLabel: recognizedStatute.officialSourceLabel
          }
        });
        continue;
      }

      const repealedRange = recognizedStatute.repealedRanges?.find(
        ([minR, maxR]) => sectionNum >= minR && sectionNum <= maxR
      );
      if (repealedRange) {
        items.push({
          rawCitation,
          normalizedCitation: `Section ${sectionToken}, ${recognizedStatute.canonicalActName}`,
          status: 'Unverified',
          evidenceOrigin: 'Local Corpus',
          evidenceBasis: 'Out-of-Range / Non-Existent Section in Known Act',
          explanation: `Section ${sectionToken} of the ${recognizedStatute.canonicalActName} falls within a repealed statutory chapter (Sections ${repealedRange[0]}–${repealedRange[1]}).`,
          limitationNote:
            'Repealed statutory sections cannot be relied upon as active authority.',
          contextSnippet,
          matchedRecord: {
            id: `statute-repealed-${recognizedStatute.canonicalActName}`,
            canonicalCitation: recognizedStatute.canonicalActName,
            actOrCaseName: recognizedStatute.canonicalActName,
            sectionOrRule: `Repealed Range: Sections ${repealedRange[0]}–${repealedRange[1]}`,
            summary: `Sections ${repealedRange[0]}–${repealedRange[1]} of ${recognizedStatute.canonicalActName} were repealed.`,
            officialSourceUrl: recognizedStatute.officialSourceUrl,
            officialSourceLabel: recognizedStatute.officialSourceLabel
          }
        });
        continue;
      }

      items.push({
        rawCitation,
        normalizedCitation: `Section ${sectionToken}, ${recognizedStatute.canonicalActName}`,
        status: 'Partially Verified',
        evidenceOrigin: 'Local Corpus',
        evidenceBasis: 'Recognized Act — Section Not in Local Corpus',
        explanation: `The enactment (${recognizedStatute.canonicalActName}) is recognized and Section ${sectionToken} falls within its enacted range (1–${recognizedStatute.maxSection}), but the verbatim text of Section ${sectionToken} is not stored in the local corpus.`,
        limitationNote:
          'Not marked Verified from local corpus alone: use "Verify with Online Research" to retrieve source evidence for Section ' +
          sectionToken +
          ' or inspect the official India Code link.',
        contextSnippet,
        matchedRecord: {
          id: `statute-only-${recognizedStatute.canonicalActName}`,
          canonicalCitation: recognizedStatute.canonicalActName,
          actOrCaseName: recognizedStatute.canonicalActName,
          sectionOrRule: `Section ${sectionToken} (Unindexed Locally)`,
          summary: `Recognized statute (${recognizedStatute.canonicalActName}); individual section text requires online retrieval or manual check on India Code.`,
          officialSourceUrl: recognizedStatute.officialSourceUrl,
          officialSourceLabel: recognizedStatute.officialSourceLabel
        }
      });
      continue;
    }

    // Step 3: Check if the citation came from the user's uploaded reference document
    if (
      uploadedReferenceText &&
      uploadedReferenceText.toLowerCase().includes(rawCitation.toLowerCase())
    ) {
      items.push({
        rawCitation,
        normalizedCitation: rawCitation,
        status: 'Partially Verified',
        evidenceOrigin: 'Uploaded Reference Document',
        evidenceBasis: 'Matched in Uploaded Reference Document Only',
        explanation: `This citation appears in your uploaded reference document, but "${actRaw}" is not indexed in the local statutory corpus.`,
        limitationNote:
          'Presence in an uploaded user document confirms file provenance, not independent official-source verification.',
        contextSnippet
      });
      continue;
    }

    // Step 4: Missing from local corpus (NOT automatically labeled fabricated!)
    items.push({
      rawCitation,
      normalizedCitation: rawCitation,
      status: 'Unverified',
      evidenceOrigin: 'None',
      evidenceBasis: 'Missing from Local Corpus — No Online Evidence Found',
      explanation: `"${rawCitation}" is not indexed in the local corpus. Missing from the local corpus does not automatically mean the citation is fabricated; run Online Source Verification to search official and legal repositories.`,
      limitationNote:
        'No local corpus record available. No source URL is invented.',
      contextSnippet
    });
  }

  // Case Law citations (e.g., "xyz v. abc (2020) 4 SCC 123" or "Hadley v. Baxendale [1854] EWHC J70")
  const caseRegex =
    /\b((?:[A-Z][A-Za-z0-9.&'-]*\s+(?:of\s+|and\s+|&\s+)?){0,3}[A-Z][A-Za-z0-9.&'-]{1,25})\s+(?:v\.|vs\.?|versus)\s+((?:[A-Z][A-Za-z0-9.&'-]*\s+(?:of\s+|and\s+|&\s+)?){0,3}[A-Z][A-Za-z0-9.&'-]{1,25})(?:\s*\(\d{4}\)\s*\d+\s*SCC\s*\d+|\s*AIR\s*\d{4}\s*[A-Z]+\s*\d+|\s*\[\d{4}\]\s*[A-Za-z0-9\s]+)?(?=[,.;:\n)]|$)/g;

  while ((match = caseRegex.exec(documentText)) !== null) {
    const rawCase = match[0].trim();
    const startIdx = match.index;
    const endIdx = startIdx + rawCase.length;

    if (isOverlapping(startIdx, endIdx)) continue;
    consumedSpans.push([startIdx, endIdx]);

    const contextSnippet = extractContextSnippet(documentText, startIdx, rawCase.length);

    const inUploadedDoc =
      uploadedReferenceText &&
      uploadedReferenceText.toLowerCase().includes(rawCase.toLowerCase());

    if (inUploadedDoc) {
      items.push({
        rawCitation: rawCase,
        normalizedCitation: rawCase,
        status: 'Partially Verified',
        evidenceOrigin: 'Uploaded Reference Document',
        evidenceBasis: 'Matched in Uploaded Reference Document Only',
        explanation:
          'This case citation was extracted from your uploaded reference document, but local judicial reporter text is not indexed.',
        limitationNote:
          'Run Online Source Verification or check official court portals to confirm the judgment text.',
        contextSnippet
      });
    } else {
      items.push({
        rawCitation: rawCase,
        normalizedCitation: rawCase,
        status: 'Unverified',
        evidenceOrigin: 'None',
        evidenceBasis: 'Missing from Local Corpus — No Online Evidence Found',
        explanation:
          'Judicial authority is not indexed in the local statutory corpus. Run Online Source Verification to retrieve judgment evidence from legal repositories.',
        limitationNote:
          'Missing from the local corpus does not imply fabrication; requires online retrieval or reporter verification.',
        contextSnippet
      });
    }
  }

  // Deduplicate repeated mentions of the same normalized authority within a single draft,
  // keeping the occurrence with the strongest contextual evidence in the document.
  const statusPriority: Record<string, number> = {
    Verified: 3,
    'Partially Verified': 2,
    Unverified: 1
  };
  const dedupedMap = new Map<string, CitationVerificationItem>();
  for (const item of items) {
    const key = item.normalizedCitation.toLowerCase();
    const existing = dedupedMap.get(key);
    if (
      !existing ||
      statusPriority[item.status] > statusPriority[existing.status]
    ) {
      dedupedMap.set(key, item);
    }
  }
  const dedupedItems = Array.from(dedupedMap.values());

  const verifiedCount = dedupedItems.filter((i) => i.status === 'Verified').length;
  const partiallyVerifiedCount = dedupedItems.filter(
    (i) => i.status === 'Partially Verified'
  ).length;
  const unverifiedCount = dedupedItems.filter((i) => i.status === 'Unverified').length;

  return {
    totalDetected: dedupedItems.length,
    verifiedCount,
    partiallyVerifiedCount,
    unverifiedCount,
    onlineResearchPerformed: false,
    items: dedupedItems,
    methodologyNote:
      'Citations are marked "Verified" only when reliable source evidence (local verbatim corpus excerpt or verified online legal source) directly supports the cited authority and relevant legal text. Plausible citation formatting or search snippets alone never establish full verification.'
  };
}
